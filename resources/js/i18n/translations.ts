export type Locale = 'en' | 'bn';

const banglaDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];

function toBanglaDigits(num: string | number): string {
    return String(num).replace(/[0-9]/g, (d) => banglaDigits[parseInt(d)]);
}

export function formatBanglaNumber(num: number): string {
    return num.toLocaleString('bn-BD');
}

export function formatCurrency(amount: number, locale: Locale): string {
    if (locale === 'bn') {
        return `৳${formatBanglaNumber(amount)}`;
    }

    return `৳${amount.toLocaleString('en-BD')}`;
}

export function formatDate(date: string | Date, locale: Locale): string {
    const d = new Date(date);

    if (locale === 'bn') {
        const day = toBanglaDigits(d.getDate());
        const month = d.toLocaleDateString('bn-BD', { month: 'long' });
        const year = toBanglaDigits(d.getFullYear());

        return `${day} ${month}, ${year}`;
    }

    return d.toLocaleDateString('en-US', {
        year: 'numeric',
        month: 'short',
        day: 'numeric',
    });
}

export function formatTime(date: string | Date, locale: Locale): string {
    const d = new Date(date);

    if (locale === 'bn') {
        return d.toLocaleTimeString('bn-BD', {
            hour: '2-digit',
            minute: '2-digit',
            hour12: true,
        });
    }

    return d.toLocaleTimeString('en-US', {
        hour: '2-digit',
        minute: '2-digit',
        hour12: true,
    });
}

